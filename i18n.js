const englishToArabic = new Map(Object.entries(copy).map(([arabic, english]) => [english, arabic]));
const root = document.documentElement;
const languageButton = document.querySelector('.language-toggle');
const themeButton = document.querySelector('.theme-toggle');
const themeMeta = document.querySelector('meta[name="theme-color"]');

function readPreference(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch { return fallback; }
}

function writePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Storage can be unavailable for local previews. */ }
}

function translateText(language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const original = node.nodeValue;
    const trimmed = original.trim();
    const translated = language === 'en' ? copy[trimmed] : englishToArabic.get(trimmed);
    if (!translated) continue;
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    node.nodeValue = `${leading}${translated}${trailing}`;
  }

  document.querySelectorAll('[aria-label], [alt], [placeholder], [title]').forEach((element) => {
    ['aria-label', 'alt', 'placeholder', 'title'].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      const translated = language === 'en' ? copy[value] : englishToArabic.get(value);
      if (translated) element.setAttribute(attribute, translated);
    });
  });
}

function setLanguage(language, persist = true) {
  const next = language === 'en' ? 'en' : 'ar';
  root.lang = next;
  root.dir = next === 'ar' ? 'rtl' : 'ltr';
  translateText(next);
  document.title = next === 'ar' ? 'IRON DISTRICT — Train with intent' : 'IRON DISTRICT — Train with intent';
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = next === 'ar'
    ? 'مساحة تدريب للقوة، التركيز، والاستمرار.'
    : 'A training space for strength, focus, and consistency.';
  if (languageButton) {
    languageButton.textContent = next === 'ar' ? 'EN' : 'عربي';
    languageButton.setAttribute('aria-label', next === 'ar' ? 'Switch language to English' : 'التبديل إلى اللغة العربية');
    languageButton.title = next === 'ar' ? 'Switch language to English' : 'التبديل إلى اللغة العربية';
  }
  window.ironLanguage = next;
  if (persist) writePreference('iron-district-language', next);
}

function setTheme(theme, persist = true) {
  const next = theme === 'light' ? 'light' : 'dark';
  root.dataset.theme = next;
  const label = next === 'dark'
    ? (root.lang === 'ar' ? 'تفعيل الوضع الفاتح' : 'Switch to light mode')
    : (root.lang === 'ar' ? 'تفعيل الوضع المظلم' : 'Switch to dark mode');
  themeButton?.setAttribute('aria-label', label);
  themeButton?.setAttribute('title', label);
  themeButton?.setAttribute('aria-pressed', String(next === 'light'));
  if (themeMeta) themeMeta.content = next === 'light' ? '#f0f2ee' : '#090a09';
  if (persist) writePreference('iron-district-theme', next);
}

setLanguage(readPreference('iron-district-language', 'ar'), false);
setTheme(readPreference('iron-district-theme', 'dark'), false);

languageButton?.addEventListener('click', () => {
  setLanguage(root.lang === 'ar' ? 'en' : 'ar');
  setTheme(root.dataset.theme);
});

themeButton?.addEventListener('click', () => {
  setTheme(root.dataset.theme === 'dark' ? 'light' : 'dark');
});

window.setIronLanguage = setLanguage;

